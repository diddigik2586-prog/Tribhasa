#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generates the Android string resources of Śodhamitra for all ten interface languages from the master tables
(tr_core.py, tr_forms.py, tr_text.py) and fails if anything is missing, duplicated or unsafe.

Usage:  python3 tools/i18n/generate_strings.py            (writes android/app/src/main/res/values*/strings.xml)
        python3 tools/i18n/generate_strings.py --check    (verifies only)
"""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import tr_core, tr_forms, tr_text   # noqa: F401  (importing fills tr_core.T)
from tr_core import T

LANGS = ["en", "kn", "sa", "te", "hi", "ta", "bn", "gu", "ml", "od"]
QUAL = {"en": "values", "kn": "values-kn", "sa": "values-sa", "te": "values-te", "hi": "values-hi",
        "ta": "values-ta", "bn": "values-bn", "gu": "values-gu", "ml": "values-ml", "od": "values-or"}
# Brand and exact-wording strings that are deliberately NOT translated (translatable="false" in values/).
FIXED = [
    ("app_name", "Śodhamitra — Research Planner"),
    ("brand_name", "Śodhamitra"),
    ("brand_tagline", "Research Planner"),
    ("copyright_line", "©Dr. Diddigi Vamsi Krishna"),
    ("pdf_footer_line1", "Śodhamitra — Research Planner"),
    ("pdf_footer_line2", "Created by © Dr. Diddigi Vamsi Krishna"),
    ("feedback_email", "dvkrishna92@gmail.com"),
    ("feedback_subject", "Śodhamitra App Feedback"),
]

def esc(s):
    s = s.replace("\\", "\\\\").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    s = s.replace("'", "\\'").replace('"', '\\"')
    if s.startswith("@") or s.startswith("?"):
        s = "\\" + s
    return s

def check():
    errs, seen = [], set()
    for row in T:
        key, vals = row[0], row[1:]
        if key in seen: errs.append("duplicate key " + key)
        seen.add(key)
        if not re.fullmatch(r"[a-z][a-z0-9_]*", key): errs.append("bad key " + key)
        for lang, v in zip(LANGS, vals):
            if not v.strip(): errs.append(f"{key}[{lang}] is empty")
        en_args = sorted(re.findall(r"%\d\$[ds]", vals[0]))
        for lang, v in zip(LANGS, vals):
            if sorted(re.findall(r"%\d\$[ds]", v)) != en_args:
                errs.append(f"{key}[{lang}] placeholder mismatch")
            if "%" in re.sub(r"%\d\$[ds]", "", v):
                errs.append(f"{key}[{lang}] stray %")
    return errs

def write(outdir):
    for i, lang in enumerate(LANGS):
        d = os.path.join(outdir, QUAL[lang]); os.makedirs(d, exist_ok=True)
        lines = ['<?xml version="1.0" encoding="utf-8"?>',
                 "<!-- GENERATED by tools/i18n/generate_strings.py from the master tables. Do not edit by hand. -->",
                 "<resources>"]
        if lang == "en":
            for k, v in FIXED:
                lines.append(f'    <string name="{k}" translatable="false">{esc(v)}</string>')
        for row in T:
            lines.append(f'    <string name="{row[0]}">{esc(row[1 + i])}</string>')
        lines.append("</resources>\n")
        open(os.path.join(d, "strings.xml"), "w", encoding="utf-8").write("\n".join(lines))

if __name__ == "__main__":
    errs = check()
    if errs:
        print("\n".join(errs)); sys.exit(1)
    print(f"{len(T)} translatable keys x {len(LANGS)} languages: complete, placeholders consistent.")
    if "--check" not in sys.argv:
        root = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "android", "app", "src", "main", "res"))
        write(root)
        print("wrote", root)
